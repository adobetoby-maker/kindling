#!/usr/bin/env python3
"""Whole-book repetition data for chapters 1-48. Pure stdlib. Usage: python3 -I whole_book_repetition.py <manuscript_dir>"""
import re, sys, os, collections
MD = sys.argv[1]
chs = {}
for n in range(1, 49):
    chs[n] = open(os.path.join(MD, f"chapter-{n:02d}.md"), encoding="utf-8").read()
alltext = "\n".join(chs.values())
def words(s): return re.findall(r"[A-Za-z0-9]+(?:['’][A-Za-z]+)?", s.lower())
TICS = ["i'd like it known", "i want it said", "i'd want it said", "i'd sooner", "on the table", "said nothing", "did not say anything",
        "tied a knot", "slowly", "scratched his jaw", "pale eyes", "nearly smiled", "went scarlet", "went red", "before the water",
        "frost on a window", "expect nothing else", "i'd not", "for a count", "that adds", "the far edge", "nobody", "kept her mouth shut",
        "since", "a hand door", "one line", "the book's", "sent for", "in two stages", "put it on the table"]
print("# Whole-book repetition data (chapters 1-48)\n")
print("Generated by provenance/tools/whole_book_repetition.py; counts are raw substring counts, case-insensitive. Heuristic, not a verdict.\n")
low = {n: t.lower() for n, t in chs.items()}
print("## Tic phrases: total, and per movement (chapters 1-8, 9-16, 17-24, 25-32, 33-40, 41-48), and top chapters\n")
print("| Phrase | Total | M1 | M2 | M3 | M4 | M5 | M6 | top chapters |\n|---|---:|---:|---:|---:|---:|---:|---:|---|")
for ph in TICS:
    per = {n: low[n].count(ph) for n in chs}
    tot = sum(per.values())
    mv = [sum(per[n] for n in range(a, a + 8)) for a in range(1, 49, 8)]
    top = ", ".join(f"{n}:{c}" for n, c in sorted(per.items(), key=lambda x: -x[1])[:4] if c)
    print(f"| {ph} | {tot} | " + " | ".join(map(str, mv)) + f" | {top} |")
# 4-gram repetition across book
toks = words(alltext)
g = collections.Counter(zip(toks, toks[1:], toks[2:], toks[3:]))
stop = set("the a an and of to in it was she he her his that i you had with on for at as but be not they them there this".split())
rows = []
for k, v in g.most_common(4000):
    if v < 14: break
    if sum(1 for w in k if w in stop) >= 3: continue
    rows.append((" ".join(k), v))
print("\n## Most repeated 4-word phrases (count >= 14, mostly-stopword phrases removed)\n")
for p, v in rows[:60]: print(f"- {p}: {v}")
# repeated identical sentences (>= 8 words) appearing in >= 2 chapters
def sents(s):
    s = re.sub(r"[*_]", "", s)
    return [x.strip() for x in re.split(r"(?<=[.!?])[\"”’')]*\s+", s) if len(x.split()) >= 8]
where = collections.defaultdict(set)
for n, t in chs.items():
    for s_ in sents(t): where[s_.lower()].add(n)
dups = [(s_, sorted(ns)) for s_, ns in where.items() if len(ns) >= 2]
print(f"\n## Identical sentences (8+ words) occurring in 2+ chapters: {len(dups)}\n")
for s_, ns in sorted(dups, key=lambda x: (-len(x[1]), x[1][0]))[:40]:
    print(f"- chapters {ns}: {s_[:150]}")
# similes: 'like a ' per chapter density
print("\n## Simile-ish density ('like a/an/the', 'as if', 'as though') per 10k words by movement\n")
for a_ in range(1, 49, 8):
    txt = " ".join(low[n] for n in range(a_, a_ + 8)); nw = len(txt.split())
    c = len(re.findall(r"\blike (a|an|the|someone|somebody|one)\b", txt)) + txt.count("as if ") + txt.count("as though ")
    print(f"- chapters {a_}-{a_+7}: {c / nw * 10000:.1f}")
